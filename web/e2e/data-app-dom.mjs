// Offline execution of the generated app's real script. Python's end-to-end test supplies the HTML on stdin.
import assert from "node:assert/strict";
import fs from "node:fs";
import { JSDOM } from "jsdom";

let proposal;
const dom = new JSDOM(fs.readFileSync(0, "utf-8"), {
  runScripts: "dangerously", // only the deterministic app generated by this repository, never uploaded HTML
  beforeParse(window) { window.postMessage = data => { proposal = data; }; },
}); // resources are disabled: no network and no API server
try {
  const document = dom.window.document;
  const search = document.querySelector("#search");
  search.value = "absent";
  search.dispatchEvent(new dom.window.Event("input"));
  assert.equal(document.querySelectorAll("tbody tr").length, 0);
  search.value = "café";
  search.dispatchEvent(new dom.window.Event("input"));
  assert.equal(document.querySelectorAll("tbody tr").length, 1);
  const cell = document.querySelector('[aria-label="Stock 1"]');
  assert.equal(cell.value, "5");
  cell.value = "12";
  cell.dispatchEvent(new dom.window.Event("input"));
  document.querySelector("#propose").click();
  assert.equal(proposal.type, "spike-data-edits");
  assert.deepEqual(JSON.parse(JSON.stringify(proposal.edits)), [{ row: 0, column: 1, value: "12" }]);
  process.stdout.write(JSON.stringify(proposal));
} finally { dom.window.close(); }
