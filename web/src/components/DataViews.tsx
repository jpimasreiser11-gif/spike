const DATA_KINDS = new Set(["data_table", "data_tables", "chart", "code_run"]);
export const isData = (ui: ToolState["ui"]): ui is DataUi => Boolean(ui && DATA_KINDS.has(ui.kind));

export function DataView({ ui }: { ui: DataUi }) {
  if (ui.kind === "chart") return <ChartView ui={ui} />;
  if (ui.kind === "code_run") return <CodeRunView ui={ui} />;
  if (ui.kind === "data_tables") return <>{ui.items.map((item, i) => <DataTableView key={i} ui={item} />)}</>;
  return <DataTableView ui={ui} />;
}

// ---------------------------------------------------------------- the report
type Item =
  | { kind: "text"; title?: string; text: string }
  | { kind: "code"; title?: string; language: string; text: string }
  | { kind: "table"; title?: string; columns: string[]; rows: unknown[][]; truncated: boolean }
  | { kind: "chart"; title?: string; spec: Record<string, unknown> };

/** The question, the answer, then every query in the order it ran with its table, chart or output. */
export function reportItems(question: string, answer: string, tools: ToolState[]): Item[] {
  const items: Item[] = [];
  if (question.trim()) items.push({ kind: "text", title: D.question, text: question });
  if (answer.trim()) items.push({ kind: "text", title: D.answer, text: answer });
  const table = (ui: DataTableUi | ChartUi, title?: string): Item => ({ kind: "table", title, columns: ui.columns, rows: ui.rows, truncated: ui.truncated });
  for (const ui of tools.map((t) => t.ui).filter(isData)) {
    if (ui.kind === "chart") {
      items.push({ kind: "chart", title: ui.title || D.result, spec: ui.spec }, { kind: "code", language: "sql", text: ui.sql }, table(ui));
    } else if (ui.kind === "code_run") {
      items.push({ kind: "code", title: D.code, language: "python", text: ui.code }, { kind: "code", title: D.output, language: "", text: ui.output });
    } else {
      for (const t of ui.kind === "data_tables" ? ui.items : [ui]) {
        items.push({ kind: "code", title: t.title || D.query, language: "sql", text: t.sql }, table(t));
      }
    }
  }
  return items;
}

const esc = (s: string) => s.replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c] as string);

const REPORT_CSS = `body{font-family:Inter,ui-sans-serif,system-ui,sans-serif;color:#13261c;background:#fff;max-width:880px;margin:0 auto;padding:24px 16px;line-height:1.5}
h1{font-size:22px;margin:0 0 4px}h2{font-size:15px;margin:22px 0 8px;color:#2a7b20}.meta,footer{color:#7b8b80;font-size:12px}
table{border-collapse:collapse;font-size:13px;margin:6px 0}th,td{border:1px solid #e2e8dd;padding:4px 8px;text-align:left}th{background:#f3f6ef}
td.num,th.num{text-align:right;font-variant-numeric:tabular-nums}pre{background:#f5f7f2;padding:10px 12px;border-radius:8px;overflow:auto;font-size:12px;white-space:pre-wrap}
svg{max-width:100%;height:auto}footer{margin-top:28px;border-top:1px solid #e2e8dd;padding-top:8px}`;

/** A self-contained page (charts as inline SVG), shown in the isolated artifact panel and downloadable. */
export async function reportHtml(title: string, items: Item[]): Promise<string> {
  const parts = [`<title>${esc(title)}</title><style>${REPORT_CSS}</style><h1>${esc(title)}</h1>`,
    `<p class="meta">${esc(D.generated)} · ${esc(new Date().toLocaleString(lang))}</p>`];
  for (const item of items) {
    if (item.title) parts.push(`<h2>${esc(item.title)}</h2>`);
    if (item.kind === "text") parts.push(markdownHtml(item.text));
    else if (item.kind === "code") parts.push(`<pre><code>${esc(item.text)}</code></pre>`);
    else if (item.kind === "chart") parts.push(await chartSvg(item.spec, 760));
    else {
      const numeric = item.columns.map((_, j) => item.rows.length > 0 && item.rows.every((r) => r[j] === null || typeof r[j] === "number"));
      parts.push(`<table><thead><tr>${item.columns.map((c, j) => `<th${numeric[j] ? ' class="num"' : ""}>${esc(c)}</th>`).join("")}</tr></thead><tbody>` +
        item.rows.map((r) => `<tr>${r.map((v, j) => `<td${numeric[j] ? ' class="num"' : ""}>${esc(fmt(v))}</td>`).join("")}</tr>`).join("") +
        `</tbody></table>${item.truncated ? `<p class="meta">${esc(rowsNote(item.rows.length, true))}</p>` : ""}`);
    }
  }
  parts.push(`<footer>${esc(D.computed)}</footer>`);
  return parts.join("\n");
}

/** Word or PDF, built by the server from the same items (charts sent as PNG). */
export async function reportFile(format: "docx" | "pdf", title: string, items: Item[]): Promise<void> {
  const blocks = [];
  for (const item of items) {
    if (item.kind === "chart") blocks.push({ kind: "image", title: item.title, png: await chartPng(item.spec) });
    else if (item.kind === "table") blocks.push({ ...item, rows: item.rows.map((r) => r.map((v) => (v === null ? null : fmt(v)))) });
    else blocks.push(item);
  }
  const res = await fetch("/api/analytics/report", {
    method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ format, title, blocks }),
  });
  if (!res.ok) {
    const detail = await res.json().then((d) => d.detail).catch(() => res.statusText);
    throw new Error(String(detail));
  }
  const name = /filename="([^"]+)"/.exec(res.headers.get("content-disposition") ?? "")?.[1] ?? `${slug(title)}.${format}`;
  const url = URL.createObjectURL(await res.blob());
  save(name, url);
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

export function ReportActions({ question, answer, tools }: { question: string; answer: string; tools: ToolState[] }) {
  const openArtifact = useContext(ArtifactContext);
  const [busy, setBusy] = useState("");
  const [error, setError] = useState("");
  const title = `${D.reportOf}: ${question.trim().split("\n")[0].slice(0, 80) || D.report}`;
  const run = (what: string, job: () => Promise<void>) => async () => {
    setBusy(what);
    setError("");
    try {
      await job();
    } catch (e) {
      setError((e as Error).message);
    } finally {
      setBusy("");
    }
  };
  const items = () => reportItems(question, answer, tools);
  const view = run("view", async () => {
    const html = await reportHtml(title, items());
    openArtifact?.({ title, html, filename: `${slug(title)}.html` });
  });
  return (
    <div className="report-actions">
      <span className="muted small">{D.report}:</span>
      <button className="btn small" disabled={Boolean(busy)} onClick={view}>{busy === "view" ? D.working : D.view}</button>
      <button className="btn small" disabled={Boolean(busy)} onClick={run("docx", () => reportFile("docx", title, items()))}>{busy === "docx" ? D.working : D.word}</button>
      <button className="btn small" disabled={Boolean(busy)} onClick={run("pdf", () => reportFile("pdf", title, items()))}>{busy === "pdf" ? D.working : D.pdf}</button>
      {error && <span className="bad small">{error}</span>}
    </div>
  );
}
