const NUMERIC = /^(U?(TINY|SMALL|BIG|HUGE)?INT(EGER)?|FLOAT|DOUBLE|REAL|DECIMAL)/i;
const isNumeric = (type: string | undefined) => NUMERIC.test(type ?? "");

export function fmt(v: unknown): string {
  if (v === null || v === undefined) return "";
  if (typeof v === "number") return v.toLocaleString(lang, { maximumFractionDigits: 6, useGrouping: Math.abs(v) >= 10000 });
  if (typeof v === "object") return JSON.stringify(v);
  return String(v);
}

function rowsNote(rows: number, truncated: boolean): string {
  return truncated ? `${D.firstRows} ${rows} ${D.rows}, ${D.more}` : `${rows} ${D.rows}`;
}

function DataTable({ columns, types, rows }: { columns: string[]; types: string[]; rows: unknown[][] }) {
  return (
    <div className="data-grid">
      <table>
        <thead><tr>{columns.map((c, i) => <th key={i} className={isNumeric(types[i]) ? "num" : ""}>{c}</th>)}</tr></thead>
        <tbody>{rows.map((r, i) => (
          <tr key={i}>{r.map((v, j) => <td key={j} className={`${isNumeric(types[j]) ? "num" : ""}${v === null ? " null" : ""}`}>{fmt(v)}</td>)}</tr>
        ))}</tbody>
      </table>
    </div>
  );
}

function tableFiles(tables: DataTableInfo[]): string {
  return [...new Set(tables.map((t) => t.file))].join(", ");
}

function SqlBlock({ sql, tables }: { sql: string; tables: DataTableInfo[] }) {
  return (
    <details className="data-sql">
      <summary>SQL{tables.length > 0 && <span className="muted"> · {tableFiles(tables)}</span>}</summary>
      <Markdown text={"```sql\n" + sql + "\n```"} />
    </details>
  );
}

function DataTableView({ ui }: { ui: DataTableUi }) {
  return (
    <section className="data-card" aria-label={ui.title || D.result}>
      <header><b>{ui.title || D.result}</b><span className="muted small">{rowsNote(ui.rows.length, ui.truncated)}</span></header>
      {ui.columns.length > 0 && <DataTable columns={ui.columns} types={ui.types} rows={ui.rows} />}
      <SqlBlock sql={ui.sql} tables={ui.tables} />
    </section>
  );
}

function save(name: string, url: string) {
  const a = document.createElement("a");
  a.href = url;
  a.download = name;
  a.click();
}

const slug = (s: string) => s.toLowerCase().normalize("NFKD").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 60) || "spike";

function ChartView({ ui }: { ui: ChartUi }) {
  const ref = useRef<HTMLDivElement>(null);
  const [error, setError] = useState("");
  const [showData, setShowData] = useState(false);
  useEffect(() => {
    const el = ref.current;
    if (!el) return;
    let view: { finalize: () => void } | null = null;
    let gone = false;
    chartView(ui.spec, { container: el, width: Math.max(240, el.clientWidth - 8) })
      .then((v) => (gone ? v.finalize() : (view = v)))
      .catch((e: Error) => setError(e.message));
    return () => {
      gone = true;
      view?.finalize();
    };
  }, [ui.spec]);
  const name = slug(ui.title || "grafico");
  const svg = async () => {
    const url = URL.createObjectURL(new Blob([await chartSvg(ui.spec)], { type: "image/svg+xml" }));
    save(`${name}.svg`, url);
    setTimeout(() => URL.revokeObjectURL(url), 1000);
  };
  const png = async () => save(`${name}.png`, await chartPng(ui.spec));
  return (
    <section className="data-card chart-card" aria-label={ui.title || D.result}>
      <div ref={ref} className="chart" role="img" aria-label={ui.title || D.result} />
      {error && <p className="bad small">{D.chartFailed}: {error}</p>}
      <div className="data-actions">
        <button className="btn small" onClick={() => setShowData(!showData)}>{showData ? D.hide : D.data}</button>
        <button className="btn small" onClick={svg}>{D.svg}</button>
        <button className="btn small" onClick={png}>{D.png}</button>
        <span className="muted small">{rowsNote(ui.rows.length, ui.truncated)}</span>
      </div>
      {showData && <DataTable columns={ui.columns} types={ui.types} rows={ui.rows} />}
      <SqlBlock sql={ui.sql} tables={ui.tables} />
    </section>
  );
}

