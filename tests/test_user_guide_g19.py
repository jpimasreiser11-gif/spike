"""G19 — User documentation in `docs/guide/` (Spanish and English).

Verifies that:
1. Index pages (`docs/guide/README.md`, `docs/guide/es/README.md`, `docs/guide/en/README.md`)
   and all 16 module pages exist in both Spanish (`docs/guide/es/`) and English (`docs/guide/en/`).
2. Each module page includes the four mandatory sections:
   - ES: `## Qué hace`, `## Cómo se usa paso a paso`, `## Límites reales`, `## Cómo comprobarlo`
   - EN: `## What it does`, `## Step-by-step usage`, `## Real limits`, `## How to verify`
3. Each module page references a real PNG screenshot generated by the smoke E2E suite.
4. All relative links and image paths inside `docs/guide/` resolve to existing files.
"""

from __future__ import annotations

import re
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[1]
GUIDE_DIR = REPO_ROOT / "docs" / "guide"

MODULES = (
    "installation",
    "chat",
    "specialists",
    "projects",
    "memory",
    "forge",
    "dev",
    "analytics",
    "design",
    "creator",
    "motion",
    "lab",
    "evolution",
    "finance",
    "connectors",
    "privacy-and-spend",
)

ES_SECTIONS = (
    "## Qué hace",
    "## Cómo se usa paso a paso",
    "## Límites reales",
    "## Cómo comprobarlo",
)

EN_SECTIONS = (
    "## What it does",
    "## Step-by-step usage",
    "## Real limits",
    "## How to verify",
)

MD_LINK_RE = re.compile(r"!?\[[^\]]*\]\(([^)]+)\)")
IMAGE_LINK_RE = re.compile(r"!\[[^\]]+\]\(([^)]+)\)")


def test_guide_indices_and_all_16_modules_exist_in_es_and_en() -> None:
    assert (GUIDE_DIR / "README.md").is_file(), "Missing docs/guide/README.md"
    assert (GUIDE_DIR / "es" / "README.md").is_file(), "Missing docs/guide/es/README.md"
    assert (GUIDE_DIR / "en" / "README.md").is_file(), "Missing docs/guide/en/README.md"

    for slug in MODULES:
        es_page = GUIDE_DIR / "es" / f"{slug}.md"
        en_page = GUIDE_DIR / "en" / f"{slug}.md"
        assert es_page.is_file(), f"Missing Spanish guide page: {es_page}"
        assert en_page.is_file(), f"Missing English guide page: {en_page}"


@pytest.mark.parametrize("slug", MODULES)
def test_guide_module_sections_and_screenshots(slug: str) -> None:
    es_page = GUIDE_DIR / "es" / f"{slug}.md"
    en_page = GUIDE_DIR / "en" / f"{slug}.md"
    es_text = es_page.read_text(encoding="utf-8")
    en_text = en_page.read_text(encoding="utf-8")

    for heading in ES_SECTIONS:
        assert heading in es_text, f"{es_page.name} (es) missing section {heading!r}"
    for heading in EN_SECTIONS:
        assert heading in en_text, f"{en_page.name} (en) missing section {heading!r}"

    for lang_code, page, text in (("es", es_page, es_text), ("en", en_page, en_text)):
        imgs = IMAGE_LINK_RE.findall(text)
        assert imgs, f"{lang_code}/{page.name} must embed at least one screenshot with non-empty alt text"
        for raw_target in imgs:
            target = raw_target.split("#", 1)[0].strip()
            img_path = (page.parent / target).resolve()
            assert img_path.is_file(), f"Missing screenshot {target!r} referenced in {lang_code}/{page.name}"
            header = img_path.read_bytes()[:8]
            assert header == b"\x89PNG\r\n\x1a\n", f"Invalid PNG header in {img_path}"


def test_all_relative_links_in_guide_resolve() -> None:
    md_files = sorted(GUIDE_DIR.rglob("*.md"))
    assert len(md_files) >= 35
    for md_file in md_files:
        text = md_file.read_text(encoding="utf-8")
        for raw_target in MD_LINK_RE.findall(text):
            target = raw_target.strip().split()[0].split("#", 1)[0]
            if not target or target.startswith(("http://", "https://", "mailto:")):
                continue
            resolved = (md_file.parent / target).resolve()
            assert resolved.exists(), f"Broken relative link {raw_target!r} in {md_file.relative_to(REPO_ROOT)}"
